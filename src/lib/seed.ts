function classAnnualTotal(className: string): number {
  return feeStructures
    .filter((f) => f.className === className)
    .reduce((s, f) => s + f.amount, 0);
}

function buildInstallments(): Installment[] {
  const rows: Installment[] = [];
  const qDates = ["2025-04-10", "2025-07-10", "2025-10-10", "2026-01-10"];
  const qNames = ["Q1", "Q2", "Q3", "Q4"];
  const halfDates = ["2025-04-15", "2025-10-15"];
  const halfNames = ["Semester 1", "Semester 2"];

  for (let c = 1; c <= 12; c++) {
    const className = `Class ${c}`;
    const total = classAnnualTotal(className);
    // Prefer quarterly for most classes; half-yearly showcase for 8 & 12
    if (c === 8 || c === 12) {
      const part = Math.round(total / 2);
      halfNames.forEach((name, i) => {
        rows.push({
          id: `ins_s${i + 1}_c${c}`,
          className,
          plan: "half_yearly",
          name,
          amount: part,
          dueDate: halfDates[i],
          academicSession: "2025-26",
        });
      });
    } else {
      const part = Math.round(total / 4);
      qNames.forEach((name, i) => {
        // Keep legacy IDs used by demo dues for Class 1, 3, 5
        const legacy =
          (c === 1 && `ins_q${i + 1}_c1`) ||
          (c === 3 && i < 2 && `ins_q${i + 1}_c3`) ||
          (c === 5 && `ins_q${i + 1}_c5`) ||
          null;
        rows.push({
          id: legacy || `ins_q${i + 1}_c${c}`,
          className,
          plan: "quarterly",
          name,
          amount: part,
          dueDate: qDates[i],
          academicSession: "2025-26",
        });
      });
    }
  }

  // Preserve extra Class 3 Q2-style continuity: dues also reference ins_q2_c3 — already included
  return rows;
}

