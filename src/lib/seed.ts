function buildFeeStructures(): FeeStructureItem[] {
  const items: FeeStructureItem[] = [];
  let n = 1;
  const add = (className: string, feeType: FeeType, amount: number) => {
    items.push({
      id: `fs_${String(n).padStart(2, "0")}`,
      className,
      feeType,
      amount,
      academicSession: "2025-26",
    });
    n += 1;
  };

  for (let c = 1; c <= 12; c++) {
    const cls = `Class ${c}`;
    const tuition = 28000 + c * 2500;
    add(cls, "Tuition Fee", tuition);
    add(cls, "Annual Fee", c <= 5 ? 4000 : c <= 8 ? 5000 : 6500);
    add(cls, "Library Fee", c <= 5 ? 1500 : c <= 10 ? 2500 : 3000);
    add(cls, "Sports Fee", c <= 5 ? 2000 : c <= 8 ? 2500 : 3500);

    if (c <= 10) {
      add(cls, "Transport Fee", 11000 + Math.floor((c - 1) / 3) * 1000);
    }
    if (c === 1 || c === 6 || c === 9 || c === 11) {
      add(cls, "Admission Fee", c <= 5 ? 5000 : c <= 8 ? 7000 : 10000);
    }
    if (c >= 6) {
      add(cls, "Laboratory Fee", c <= 8 ? 4000 : c <= 10 ? 6000 : 9000);
    }
    if (c >= 5) {
      add(cls, "Examination Fee", c <= 8 ? 2500 : c <= 10 ? 3500 : 5000);
    }
  }
  return items;
}

